class PipelineInterrupted(KeyboardInterrupt):
    """CLI termination request, recorded through the normal interrupted-run path."""


def main(argv: list[str] | None = None) -> int:
    """Install signal handling only for the CLI, restoring the caller's handler afterwards."""
    if threading.current_thread() is not threading.main_thread():
        return _main(argv)
    previous = signal.getsignal(signal.SIGTERM)

    def interrupted(signum, frame):
        # Let the first termination request finish publishing the failure record.
        # The batch supervisor can still enforce its hard deadline with SIGKILL.
        signal.signal(signal.SIGTERM, signal.SIG_IGN)
        raise PipelineInterrupted(f"received signal {signum}")

    signal.signal(signal.SIGTERM, interrupted)
    try:
        return _main(argv)
    except KeyboardInterrupt:
        return 130
    finally:
        signal.signal(signal.SIGTERM, previous)


def _main(argv: list[str] | None = None) -> int:
    ap = build_parser()
    args = ap.parse_args(argv)
    # Enable download and tile-loop progress with run identifiers unless logging is already configured.
    configure_logging(args.quiet)
    if args.list_components:
        print(spec.usage_summary())
        return 0
    if not args.slide:
        ap.error("--slide is required (or use --list_components)")
    if args.no_metadata and (args.metadata or args.metadata_key):
        ap.error("--no_metadata cannot be combined with --metadata/--metadata_key; "
                 "one skips the lookup, the other configures it")
    if args.metadata_key and not args.metadata:
        # Everything else is validated before the slide is opened; a flag that quietly does nothing
        # is exactly the failure this pre-flight exists to prevent.
        ap.error("--metadata_key only applies to --metadata files; pass --metadata PATH too")

    selected = {k for k in spec.COMPONENTS if getattr(args, f"run_{k}")}
    aliases = {a for a in spec.ALIASES if getattr(args, a.lstrip("-"))}
    supplied = {n: getattr(args, f"in_{n}") for n in spec.ARTIFACTS
                if getattr(args, f"in_{n}")}
    run_set = spec.resolve_run_set(selected, aliases)
    # run() plans with the resolved backend configuration. Planning errors raise ValueError;
    # warnings reach the callback before slide I/O.

    def _warn(message):
        print(f"warning: {message}", file=sys.stderr)

    try:
        r = run(args.slide, out_dir=args.out, stain_type=args.stain, bank=args.bank,
                norm_method=args.norm_method, components=run_set, supplied=supplied,
                grandqc_repo=args.grandqc_repo, grandqc_python=args.grandqc_python,
                pen_weights=args.pen_weights, save_artifacts=not args.no_save_artifacts,
                metadata_paths=args.metadata, metadata_key=args.metadata_key,
                metadata_enabled=False if args.no_metadata else None, warn=_warn,
                download_models=not args.no_model_download)
    except RunFailed as exc:
        # Processing failures exit 1 and retain available reports; invalid arguments exit 2.
        f = exc.failure
        print(f"error: run failed during {f['stage']}: {f['type']}: {f['message']}", file=sys.stderr)
        if f["type"] in ("RuntimeError",) and ("could not open" in f["message"]
                                              or "could not localize" in f["message"]):
            print(f"  --slide expects a readable WSI path: a local file or GCS, S3 or Azure object URI.\n"
                  f"  got: {args.slide}", file=sys.stderr)
        if exc.report_path:
            print(f"report (FAILED run; see its `error` block) -> {exc.report_path}", file=sys.stderr)
        return 1
    except (RuntimeError, ValueError) as exc:
        # Pre-flight refusal: a bad command, nothing touched, nothing written.
        print(f"error: {exc}", file=sys.stderr)
        return 2
    except Exception as exc:  # noqa: BLE001 - a bug in the pipeline, not in the command: exit 1
        print(f"error: {type(exc).__name__}: {exc}", file=sys.stderr)
        traceback.print_exc()
        return 1

    rep = r["report"]
    print(f"components: {', '.join(sorted(run_set))}")
    rd = rep["m2"].get("read") or {}
    if rd.get("level") is not None:
        print(f"read: {rd['target_mpp']} um/px from L{rd['level']} "
              f"({rd['direction']} x{rd['resample_ratio']:.4f}) -> plane {rd['plane_dims']}")
    elif rd:
        print(f"read: {rd.get('source')}: {rd.get('error') or rd.get('note')}")
    tm = rep["timing"]
    print(f"timing: total {tm['total_s']:.1f}s  " +
          " · ".join(f"{k} {v}" for k, v in tm["stages"].items() if v))
    for name, meta in (rep["provenance"].get("outputs") or {}).items():
        print(f"  wrote {name}: {meta.get('path')}")
    print(f"report -> {r['report_path']}")
    if r.get("out_dir") and (Path(r["out_dir"]) / "index.html").is_file():
        print(f"browse -> {Path(r['out_dir']) / 'index.html'}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
