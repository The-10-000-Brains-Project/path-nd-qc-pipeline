"""Run selected Path-ND QC components on a single slide.

    pathnd-qc --slide slide.svs --run_tissue_segmentation
    pathnd-qc --slide slide.svs --tissue_mask mask.png --run_fold_detection
    pathnd-qc --list_components

Components consume artifacts declared in ``pipeline_spec.py``. The thumbnail, three masks and
selected tile list can be supplied from files; other outputs are generated by their producers.
Known argument and supplied-file errors are checked before slide reads. Geometry, remote access
and model failures can still occur during processing. Reports and partial outputs are saved on a
best-effort basis, including on failure when the destination remains writable.

Local, GCS, S3 and Azure slides share the reader. Tile reads use a localized copy; M2/M4 normally
stream an analysis plane, with localization for remote inputs that require banded reading.
Default target scales are 8.0 microns/pixel for M2/M4 and 0.5 for M3. Integer dimensions introduce
rounding, and common scale alone does not establish scientific comparability.

Metadata lookup uses only user-supplied CSV paths. No paths means no lookup. M4's shipped reference
targets are placeholders, not calibrated neuropathology references. See USAGE_CLI.md for contracts.
"""
